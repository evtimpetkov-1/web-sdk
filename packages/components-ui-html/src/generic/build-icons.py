#!/usr/bin/env python3
"""Writes icons.ts from icon-src/*.png (the studio's white icon set, cut off the
grey discs of Kraken's Wilds' button sheet) plus a few glyphs that set never had
(chevrons, a music note), as data URIs. The UI draws them as CSS masks, so only
their alpha matters and any colour can be laid through them.
    python3 build-icons.py
"""
import base64, io, pathlib
from PIL import Image

HERE = pathlib.Path(__file__).parent
SIZE = {"spin_icon": 144}
NAMES = {"auto": "auto", "close": "close", "info": "info", "menu": "menu", "minus": "minus", "plus": "plus",
         "sound_on": "soundOn", "sound_off": "soundOff", "spin_icon": "spin", "stop": "stop", "turbo": "turbo"}
SVG = {
    "chevronUp": '<path d="M5 15.5 12 8.5l7 7" fill="none" stroke="#fff" stroke-width="3.2" stroke-linecap="round" stroke-linejoin="round"/>',
    "chevronDown": '<path d="M5 8.5l7 7 7-7" fill="none" stroke="#fff" stroke-width="3.2" stroke-linecap="round" stroke-linejoin="round"/>',
    "music": '<path d="M9 4.2 20 2v13.2a3.3 3.3 0 1 1-2.2-3.1V6.9L11.2 8.2v9.1A3.3 3.3 0 1 1 9 14.2z" fill="#fff"/>',
    "musicOff": '<path d="M9 4.2 20 2v13.2a3.3 3.3 0 1 1-2.2-3.1V6.9L11.2 8.2v9.1A3.3 3.3 0 1 1 9 14.2z" fill="#fff"/><path d="M3 3l18 18" stroke="#fff" stroke-width="2.4" stroke-linecap="round"/>',
    "check": '<path d="M4.5 12.5l5 5 10-11" fill="none" stroke="#fff" stroke-width="3.2" stroke-linecap="round" stroke-linejoin="round"/>',
}
lines = ["// GENERATED by build-icons.py: do not edit by hand", "export const ICONS = {"]
for file, name in NAMES.items():
    n = SIZE.get(file, 80)
    im = Image.open(HERE / "icon-src" / f"{file}.png").convert("RGBA").resize((n, n), Image.LANCZOS)
    alpha = im.split()[3]
    out = Image.merge("LA", (Image.new("L", im.size, 255), alpha))
    buf = io.BytesIO(); out.save(buf, "PNG", optimize=True)
    lines.append(f"\t{name}: 'data:image/png;base64,{base64.b64encode(buf.getvalue()).decode()}',")
for name, body in SVG.items():
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24">{body}</svg>'
    lines.append(f"\t{name}: 'data:image/svg+xml;base64,{base64.b64encode(svg.encode()).decode()}',")
lines += ["} as const;", "", "export type IconName = keyof typeof ICONS;", ""]
(HERE / "icons.ts").write_text("\n".join(lines))
print("icons.ts", (HERE / "icons.ts").stat().st_size, "bytes")
